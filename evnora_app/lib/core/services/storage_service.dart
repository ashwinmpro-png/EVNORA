class StorageService {
  static late Box _userBox;
  static late Box _jobsBox;
  static late Box _programsBox;
  static late Box _settingsBox;
  static late Box _cacheBox;
  static late SharedPreferences _prefs;
  static const _secureStorage = FlutterSecureStorage(
    aOptions: AndroidOptions(encryptedSharedPreferences: true),
    iOptions: IOSOptions(accessibility: KeychainAccessibility.first_unlock),
  );

  // Initialize storage
  static Future<void> init() async {
    // Register Hive adapters
    _registerAdapters();
    
    // Open Hive boxes
    _userBox = await Hive.openBox(AppConstants.userBox);
    _jobsBox = await Hive.openBox(AppConstants.jobsBox);
    _programsBox = await Hive.openBox(AppConstants.programsBox);
    _settingsBox = await Hive.openBox(AppConstants.settingsBox);
    _cacheBox = await Hive.openBox(AppConstants.cacheBox);
    
    // Initialize SharedPreferences
    _prefs = await SharedPreferences.getInstance();
  }

  static void _registerAdapters() {
    // Register all Hive type adapters here
    // These will be generated by hive_generator
    // Hive.registerAdapter(UserAdapter());
